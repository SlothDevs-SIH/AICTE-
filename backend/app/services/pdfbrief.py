"""Joint Case Brief PDF (MASTER_PLAN U9): one page that both units can read before they talk."""
import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.services.summary import facts, template


def brief_pdf(db, overlap, generated_by: str) -> bytes:
    f = facts(db, overlap)
    st = getSampleStyleSheet()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm,
                            bottomMargin=16 * mm, title="Joint Case Brief")
    P = lambda t, s="BodyText": Paragraph(escape(t), st[s])  # noqa: E731
    cell = lambda t: Paragraph(escape(str(t)), st["BodyText"])  # noqa: E731
    el = [P("SYNTHETIC DATA - generated for demonstration only", "Heading4"),
          P("Joint Case Brief", "Title"),
          P(f"{f['institution']}", "Heading2"),
          P("Potential Overlapping Cases - Coordination Required", "Heading3"),
          P(f"Severity: {f['severity']} | Rule type: {f['type']} | Status: {overlap.status}"),
          Spacer(1, 6)]
    rows = [["", f["a"]["unit"], f["b"]["unit"]]]
    for label, key in (("Case ID", "case_id"), ("Category", "category"), ("Status", "state"),
                       ("Received", "received"), ("Last action", "last_action")):
        rows.append([label, cell(f["a"][key]), cell(f["b"][key])])
    t = Table(rows, colWidths=[30 * mm, 70 * mm, 70 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), .5, colors.grey), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f4d3a")),
                           ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    el += [t, Spacer(1, 10), P("Why this was suggested", "Heading3")]
    el += [P("- " + r) for r in f["reasons"]]
    el += [P("Wording similarity is not part of this match. " + overlap.receipt_json["layers"]["L3_issue"]["formula"]),
           Spacer(1, 8), P("Summary", "Heading3"), P(template(f)), Spacer(1, 12),
           P(f"Suggested by the system for officer review. It has not been acted on. Generated by {generated_by}.", "Italic")]
    doc.build(el)
    return buf.getvalue()
